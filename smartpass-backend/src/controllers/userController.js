const userService = require('../services/userService');

const getUsers = async (req, res, next) => {
  try {
    const result = await userService.getUsers({
      q: req.query.q,
      page: req.query.page,
      limit: req.query.limit,
    });
    res.status(200).json({
      success: true,
      data: result.data,
      pagination: result.pagination,
    });
  } catch (error) {
    next(error);
  }
};

